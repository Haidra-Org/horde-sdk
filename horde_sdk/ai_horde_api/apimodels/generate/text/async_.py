class ContextFit(StrEnum):
    """What the horde does when a request's prompt does not fit the context it asked for."""

    ignore = auto()
    """Send it anyway. The worker truncates the front of the prompt."""

    reject = auto()
    """Refuse the request rather than have the worker cut the front of the prompt away."""

    grow = auto()
    """Raise `max_context_length` until the prompt fits, and charge for the larger context.

    When no online text worker serves the request's models there is nothing to grow into, so a prompt
    that does not fit is refused with `PromptExceedsContext` at the requested size."""


class TextGenerateAsyncResponse(
    HordeResponseBaseModel,
    JobResponseMixin,
    ResponseRequiringFollowUpMixin,
    ContainsMessageResponseMixin,
):
    """The expected cost of the requested job and any warnings generated by the server.

    Represents the data returned from the /v2/generate/text/async endpoint with http status code 202.

    v2 API Model: `RequestAsync`
    """

    kudos: float | None = Field(
        default=None,
    )
    """The expected kudos consumption for this request."""
    warnings: list[SingleWarningEntry] | None = None
    """Any warnings that were generated by the server or a serving worker."""

    @model_validator(mode="after")
    def validate_warnings(self) -> TextGenerateAsyncResponse:
        """Log any warnings that were generated by the server or a serving worker."""
        if self.warnings is None:
            return self

        for warning in self.warnings:
            logger.warning(f"Warning from server ({warning.code}): {warning.message}")

        return self

    @override
    def get_follow_up_returned_params(self, *, as_python_field_name: bool = False) -> list[dict[str, object]]:
        if as_python_field_name:
            return [{"id_": self.id_}]
        return [{"id": self.id_}]

    @override
    @classmethod
    def get_follow_up_default_request_type(cls) -> type[TextGenerateStatusRequest]:
        return TextGenerateStatusRequest

    @override
    @classmethod
    def get_follow_up_request_types(  # type: ignore[override]
        cls,
    ) -> list[type[TextGenerateStatusRequest]]:
        return [TextGenerateStatusRequest]

    @override
    @classmethod
    def get_follow_up_failure_cleanup_request_type(cls) -> type[DeleteTextGenerateRequest]:
        return DeleteTextGenerateRequest

    @override
    @classmethod
    def get_api_model_name(cls) -> str | None:
        return "RequestAsync"

    def __hash__(self) -> int:
        return hash(TextGenerateAsyncResponse.__name__) + hash(self.id_)

    def __eq__(self, __value: object) -> bool:
        return isinstance(__value, TextGenerateAsyncResponse) and self.id_ == __value.id_


